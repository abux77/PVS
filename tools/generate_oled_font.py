#!/usr/bin/env python3
"""Generate fixed monochrome glyphs; Pillow needed only to regenerate the font."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
root = Path(__file__).resolve().parents[1]
font = ImageFont.truetype(str(root/'assets/fonts/Audiowide-Regular.ttf'),16)
rows=[]
glyphs={}
digit_width=max(round(font.getlength(c)) for c in "0123456789")
for code in range(32,127):
    ch=chr(code)
    natural=round(font.getlength(ch))
    advance=digit_width if ch.isdigit() else natural
    glyph=Image.new('L',(32,16))
    ImageDraw.Draw(glyph).text(((advance-natural)//2,-3),ch,font=font,fill=255)
    columns=[sum((1<<y) for y in range(16) if glyph.getpixel((x,y))>=128) for x in range(advance)]
    # Thicken strokes downward by one pixel, preserving letter spacing.
    columns=[(column | (column << 1)) & 0xffff for column in columns]
    glyphs[ch]=columns
    assert advance<=24
    rows.append('    {%d,{%s}},' % (advance,','.join(str(c) for c in columns)))
(root/'src/oled_font.h').write_text('/* Generated by tools/generate_oled_font.py PVS Display bitmap derived from Audiowide Regular.\n * Copyright 2012 Brian J. Bonislawsky DBA Astigmatic (AOETI). SIL OFL 1.1: assets/fonts/OFL.txt. */\n#pragma once\n#include <stdint.h>\ntypedef struct { uint8_t width; uint16_t columns[24]; } oled_glyph_t;\nstatic const oled_glyph_t oled_font[95] = {\n'+'\n'.join(rows)+'\n};\n')
# Check every fixed label and maximum-width numeric field used by the UI.
for label in ("CHROMATIC", "PARAMETER", "FIRMWARE", "EJECT FILES",
              "SAVE FILES", "THROAT 255", "MOUTH 255", "88200 HZ",
              "PRESET", "STORED", "LOADED", "BUILD 999", "BANK 12"):
    assert sum(len(glyphs[c]) for c in label)<=128, label
preview=Image.new('1',(128*3,64))
for panel,lines in enumerate([('NORMAL','SPEED 072','PITCH 096'),('SAMPLE','22050 HZ','8 BIT'),('VOICE','MOUTH 128','THROAT 128')]):
    for y,text in zip((2,46,24),lines):
        image=Image.new('1',(128,16))
        width=sum(len(glyphs[c]) for c in text)
        assert width<=128, text
        x=(128-width)//2
        for c in text:
            for column in glyphs[c]:
                for bit in range(16):
                    if column & (1<<bit): image.putpixel((x,bit),255)
                x+=1
        preview.paste(image,(panel*128,y))
preview.resize((1152,192),Image.Resampling.NEAREST).save(root/'docs/OLED_PREVIEW.png')
