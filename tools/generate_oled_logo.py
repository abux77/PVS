#!/usr/bin/env python3
"""Pack the user-provided logo into the SSD1306's 128x64 page layout."""
from pathlib import Path
from PIL import Image, ImageOps
root=Path(__file__).resolve().parents[1]
source=Image.open(root/'assets/pvs-logo.png').convert('L')
# Remove black margins, preserving the complete lettering and underline.
bounds=source.point(lambda p:255 if p>80 else 0).getbbox()
if bounds: source=source.crop(bounds)
source=ImageOps.contain(source,(124,60),Image.Resampling.LANCZOS)
screen=Image.new('L',(128,64))
screen.paste(source,((128-source.width)//2,(64-source.height)//2))
screen=screen.point(lambda p:255 if p>=90 else 0).convert('1')
data=[sum(1<<bit for bit in range(8) if screen.getpixel((x,page*8+bit))) for page in range(8) for x in range(128)]
text='/* Generated by tools/generate_oled_logo.py; source assets/pvs-logo.png. Logo: CC BY-NC 4.0, Andrew Buckie; see assets/LOGO_LICENSE.md. */\n#pragma once\n#include <stdint.h>\nstatic const uint8_t oled_boot_logo[1024] = {\n'
text+='\n'.join('    '+','.join(f'0x{v:02x}' for v in data[i:i+16])+',' for i in range(0,len(data),16))
(root/'src/oled_logo.h').write_text(text+'\n};\n')
screen.resize((768,384),Image.Resampling.NEAREST).save(root/'docs/OLED_BOOT_PREVIEW.png')
